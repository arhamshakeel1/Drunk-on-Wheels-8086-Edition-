curve_sample:
 or ax,ax
 jns .positive
 xor ax,ax
.positive:
 cmp ax,16383
 jbe .index
 mov ax,16383
.index:
 mov bx,ax
 and ax,63
 mov cl,6
 shr bx,cl
 shl bx,1
 mov cx,[routeLine+bx+2]
 sub cx,[routeLine+bx]
 imul cx
 mov cl,6
 ; Signed product >> 6; the segment step is bounded by route design.
 sar ax,cl
 add ax,[routeLine+bx]
 ret
prepare_bend:
 mov ax,[pz]
 sub ax,[camBack]
 mov [camZ],ax
 call curve_sample
 mov [camLine],ax
 ; Central difference avoids a visible yaw step at a spline sample.
 mov ax,[camZ]
 add ax,32
 call curve_sample
 push ax
 mov ax,[camZ]
 sub ax,32
 call curve_sample
 pop bx
 sub bx,ax
 mov ax,bx
 ; Keep the yaw correction in eighths of a pixel.
 mov bx,3
 imul bx
 sar ax,1
 mov [yawSubpixels],ax
 ret
; Store the centreline offset in eighths of a pixel at camera depth AX.
bend_offset:
 mov word [bendSubpixels],0
 cmp byte [level],PARKING
 je .done
 push ax
 add ax,[camZ]
 call curve_sample
 sub ax,[camLine]
 mov cx,96                  ; FOCAL * 8 / 16
 imul cx
 pop bx
 idiv bx
 sub ax,[yawSubpixels]
 mov [bendSubpixels],ax
.done:
 ret
